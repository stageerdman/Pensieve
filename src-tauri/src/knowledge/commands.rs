// The Tauri commands the frontend calls to manage one agent's knowledge files, plus
// retrieve_for_agent — not a command, the plain function assistant.rs calls internally
// before every reply.

use serde::Serialize;
use tauri::{AppHandle, Emitter};

use super::chunk::chunk_text;
use super::embedder::{embed_many, embed_one};
use super::extract::extract_text;
use super::paths::{agent_db_path, agent_knowledge_dir};
use super::store::{count_chunks_for_file, delete_file_chunks, has_any_chunks, insert_file_chunks, open_db, search, RetrievedChunk};

#[derive(Serialize)]
pub struct KnowledgeFileMeta {
    pub id: String,
    pub name: String,
    pub size: u64,
    #[serde(rename = "type")]
    pub kind: String,
    #[serde(rename = "chunkCount")]
    pub chunk_count: usize,
}

#[derive(Serialize, Clone)]
struct KnowledgeIngestProgress {
    #[serde(rename = "jobId")]
    job_id: String,
    processed: usize,
    total: usize,
}

fn emit_ingest_progress(app: &AppHandle, job_id: &str, processed: usize, total: usize) {
    let _ = app.emit("knowledge-ingest-progress", KnowledgeIngestProgress { job_id: job_id.to_string(), processed, total });
}

fn file_extension(file_name: &str) -> String {
    std::path::Path::new(file_name).extension().and_then(|e| e.to_str()).unwrap_or("").to_lowercase()
}

// How many chunks to embed per fastembed call — small enough that the frontend sees
// real incremental progress on a large file, large enough that batching still beats
// embedding one chunk at a time.
const EMBED_BATCH_SIZE: usize = 16;

// Copies a knowledge file in, extracts its text, chunks it, embeds every chunk locally,
// and stores the result in the agent's own knowledge database — everything this agent
// will ever "know" from this file from now on. `file_id` is generated by the frontend
// (same pattern as every other id in this app), so it's stable for this one call and
// for later removal.
#[tauri::command]
pub async fn ingest_knowledge_file(
    app: AppHandle,
    job_id: String,
    agent_id: String,
    file_id: String,
    source_path: String,
    file_name: String,
) -> Result<KnowledgeFileMeta, String> {
    tauri::async_runtime::spawn_blocking(move || -> Result<KnowledgeFileMeta, String> {
        let source = std::path::Path::new(&source_path);
        let size = std::fs::metadata(source).map(|m| m.len()).unwrap_or(0);

        let knowledge_dir = agent_knowledge_dir(&app, &agent_id)?;
        std::fs::create_dir_all(&knowledge_dir).map_err(|e| format!("Couldn't create the agent's knowledge folder: {e}"))?;
        let stored_path = knowledge_dir.join(format!("{file_id}_{file_name}"));
        std::fs::copy(source, &stored_path).map_err(|e| format!("Couldn't store a copy of this file: {e}"))?;

        let text = extract_text(&stored_path)?;
        let chunks = chunk_text(&text);
        if chunks.is_empty() {
            return Err("This file had no readable text to learn from.".to_string());
        }
        let total = chunks.len();
        emit_ingest_progress(&app, &job_id, 0, total);

        let db_path = agent_db_path(&app, &agent_id)?;
        let conn = open_db(&db_path)?;

        // Embedded and stored in small batches (not all at once) so the frontend sees
        // real incremental progress on a large file instead of one long silence
        // followed by "done".
        let mut processed = 0;
        for batch in chunks.chunks(EMBED_BATCH_SIZE) {
            let batch_texts: Vec<String> = batch.to_vec();
            let embeddings = embed_many(&app, batch_texts.clone())?;
            let paired: Vec<(String, Vec<f32>)> = batch_texts.into_iter().zip(embeddings).collect();
            insert_file_chunks(&conn, &file_id, &file_name, &paired)?;
            processed += batch.len();
            emit_ingest_progress(&app, &job_id, processed, total);
        }
        let chunk_count = count_chunks_for_file(&conn, &file_id)?;

        Ok(KnowledgeFileMeta { id: file_id, name: file_name.clone(), size, kind: file_extension(&file_name), chunk_count })
    })
    .await
    .map_err(|e| format!("Internal error indexing this file ({e})."))?
}

// Removes a knowledge file's stored copy and every chunk/vector it produced.
#[tauri::command]
pub async fn remove_knowledge_file(app: AppHandle, agent_id: String, file_id: String, file_name: String) -> Result<(), String> {
    tauri::async_runtime::spawn_blocking(move || -> Result<(), String> {
        let db_path = agent_db_path(&app, &agent_id)?;
        if db_path.exists() {
            let conn = open_db(&db_path)?;
            delete_file_chunks(&conn, &file_id)?;
        }
        let knowledge_dir = agent_knowledge_dir(&app, &agent_id)?;
        let _ = std::fs::remove_file(knowledge_dir.join(format!("{file_id}_{file_name}")));
        Ok(())
    })
    .await
    .map_err(|e| format!("Internal error removing this file ({e})."))?
}

// Used internally by assistant.rs before every reply. Returns an empty list (not an
// error) whenever an agent has no indexed knowledge at all, so callers can always just
// check `.is_empty()` instead of separately branching on "does this agent even have
// knowledge files."
pub fn retrieve_for_agent(app: &AppHandle, agent_id: &str, query: &str, top_k: usize) -> Result<Vec<RetrievedChunk>, String> {
    let db_path = agent_db_path(app, agent_id)?;
    if !db_path.exists() {
        return Ok(Vec::new());
    }
    let conn = open_db(&db_path)?;
    if !has_any_chunks(&conn)? {
        return Ok(Vec::new());
    }
    let query_embedding = embed_one(app, query)?;
    search(&conn, &query_embedding, top_k)
}
